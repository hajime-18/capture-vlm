"""VLMへの指示文"""

INSTRUCTION = """あなたは考古学の発掘調査報告書をデジタル化する専門家です。
添付のページ画像と、その後に続くOCR結果(JSON)をもとに、このページの内容をMarkdown形式に変換してください。

## 変換ルール
1. 本文の文字はOCR結果を基本とし、誤認識・脱字・改行の乱れは画像を見て正しく修正すること。
2. 章・節・項などの見出しは、階層に応じて #, ##, ### を使い分けること。
3. 表(遺構一覧表、遺物観察表など)はMarkdownの表形式で再現し、行と列の対応を崩さないこと。
4. 図・写真・実測図は内容を推測せず、キャプションのみを「![キャプション]()」の形で記載すること。
5. 遺跡名・遺構番号(SK01, SD02 等)・遺物番号・数値・単位・時代名・土層名は画像通り正確に記載すること。
6. 縦書きの場合は正しい読み順(右の行から左の行へ)に並べ直すこと。
7. ページ番号・柱(ページ上部の章題などの繰り返し表記)は出力しないこと。
8. 画像にもOCR結果にも無い情報は追加しないこと。判読できない文字は「〓」とすること。

## 出力形式
- 出力はMarkdown本文のみとすること。
- 前置き、説明、感想、コードブロックの囲み(```)は一切出力しないこと。

## OCR結果(JSON)
"""


def build_prompt(ocr_text: str) -> str:
    return INSTRUCTION + ocr_text